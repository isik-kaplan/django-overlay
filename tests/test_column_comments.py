"""Columns django-overlay adds carry a comment, and a comment can be changed
on a column the overlay view selects."""

import pytest
from django.db import connection, migrations, models
from django.db.migrations.state import ModelState, ProjectState
from django.test.utils import isolate_apps

from django_overlay.management.commands.makemigrations import _comment_aware_alter_fields
from django_overlay.models import OverlayMeta, OverlayModel
from django_overlay.operations import AlterOverlayField
from django_overlay.sources import SourceTable
from django_overlay.strategies import Strategy


@isolate_apps("tests.testapp")
@pytest.mark.parametrize("strategy", list(Strategy))
@pytest.mark.parametrize("soft_delete", [True, False])
def test_every_column_the_library_adds_has_a_help_text_and_a_comment(strategy, soft_delete):
    """Walks whatever the base model has beyond the declared column, so a
    column added later can't skip this. A Django auto field is not the
    library's to annotate and is left out."""

    def get_source():
        return SourceTable(schema="public", table="testapp_shared_personsource")

    overlay_meta = type(
        "OverlayMeta",
        (OverlayMeta.with_strategy(strategy),),
        {"get_source": staticmethod(get_source), "soft_delete": soft_delete, "table_name": "commented"},
    )
    model = type(
        "Commented",
        (OverlayModel,),
        {
            "__module__": __name__,
            "Meta": type("Meta", (), {"app_label": "testapp"}),
            "OverlayMeta": overlay_meta,
            "name": models.CharField(max_length=10),
        },
    )

    added = [
        field
        for field in model.base_table()._meta.local_fields
        if field.name != "name" and not isinstance(field, models.AutoField)
    ]
    assert [field.name for field in added] == (["id"] if strategy.value.startswith("uuid") else []) + (
        ["_overlay_deleted"] if soft_delete else []
    )
    for field in added:
        assert field.help_text and field.db_comment == field.help_text


@pytest.mark.django_db
def test_the_comments_reached_columns_the_view_selects():
    """Migration 0035 is a comment-only AlterOverlayField on columns
    person_uuid4_view selects; a plain AlterField there is refused by Postgres."""
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT a.attname, col_description(a.attrelid, a.attnum) FROM pg_attribute a "
            "WHERE a.attrelid = 'person_uuid4'::regclass AND a.attname IN ('id', '_overlay_deleted') "
            "ORDER BY a.attname"
        )
        comments = dict(cursor.fetchall())
    assert comments["id"].startswith("Primary key generated by django-overlay")
    assert comments["_overlay_deleted"].startswith("Set by django-overlay")


def _states(old_field, new_field, managed=True):
    def state(field):
        project = ProjectState()
        project.add_model(
            ModelState(
                "probe",
                "thing",
                [("id", models.AutoField(primary_key=True)), ("flag", field)],
                options={"managed": managed},
            )
        )
        return project

    return state(old_field), state(new_field)


def _sql(old_field, new_field, backwards=False, managed=True):
    before, after = _states(old_field, new_field, managed)
    operation = AlterOverlayField("thing", "flag", new_field)
    with connection.schema_editor(collect_sql=True) as editor:
        if backwards:
            operation.database_backwards("probe", editor, after, before)
        else:
            operation.database_forwards("probe", editor, before, after)
    return editor.collected_sql


@pytest.mark.django_db
def test_a_comment_only_change_is_just_a_comment():
    sql = _sql(models.BooleanField(default=False), models.BooleanField(default=False, db_comment="new"))

    assert sql == ['COMMENT ON COLUMN "probe_thing"."flag" IS \'new\';']


@pytest.mark.django_db
def test_a_comment_only_change_reverses_to_the_old_comment():
    sql = _sql(
        models.BooleanField(default=False, db_comment="old"),
        models.BooleanField(default=False, db_comment="new"),
        backwards=True,
    )

    assert sql == ['COMMENT ON COLUMN "probe_thing"."flag" IS \'old\';']


@pytest.mark.django_db
def test_any_other_change_is_left_to_alter_field():
    sql = _sql(models.IntegerField(null=True), models.BigIntegerField(null=True, db_comment="new"))

    assert any("TYPE bigint" in statement for statement in sql)


@pytest.mark.django_db
def test_a_change_that_reaches_no_column_runs_nothing():
    assert _sql(models.BooleanField(default=False), models.BooleanField(default=False, help_text="h")) == []


@pytest.mark.django_db
def test_an_unmanaged_model_is_left_alone():
    sql = _sql(models.BooleanField(), models.BooleanField(db_comment="new"), managed=False)

    assert sql == []


def test_makemigrations_writes_an_alter_field_on_a_base_table_as_an_alter_overlay_field():
    field = models.BooleanField(db_comment="c")
    operations = [
        migrations.AlterField("PersonBase", "flag", field),
        migrations.AlterField("Plain", "flag", field),
        migrations.AddField("PersonBase", "other", field),
    ]

    rewritten = _comment_aware_alter_fields(operations, {"personbase": "Person"})

    assert [type(op) for op in rewritten] == [AlterOverlayField, migrations.AlterField, migrations.AddField]
    assert (rewritten[0].model_name, rewritten[0].name, rewritten[0].field) == ("PersonBase", "flag", field)


@pytest.mark.django_db
def test_a_unique_index_still_waiting_to_be_created_is_not_restored_twice():
    """In a squashed migration the CreateModel and the AlterOverlayField share
    one schema editor, and a conditional UniqueConstraint -- the shape soft
    delete gives every uniqueness rule -- is created at its end; restoring it
    before then would create it twice."""
    from django_overlay.operations import _restore_unique_indexes

    project = ProjectState()
    project.add_model(
        ModelState(
            "probe",
            "pending",
            [("id", models.AutoField(primary_key=True)), ("code", models.IntegerField())],
            options={
                "constraints": [
                    models.UniqueConstraint(fields=["code"], condition=models.Q(code__gt=0), name="pending_code_uniq")
                ]
            },
        )
    )
    model = project.apps.get_model("probe", "pending")
    with connection.schema_editor(collect_sql=True) as editor:
        editor.create_model(model)
        _restore_unique_indexes(editor, model, model._meta.get_field("code"))

    assert sum("pending_code_uniq" in sql for sql in editor.collected_sql) == 1
