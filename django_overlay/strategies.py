import enum
import uuid

from django.db import models

from ._templating import render
from .uuid7 import uuid7


class Strategy(enum.Enum):
    """How an organically-created row gets an id that can never collide
    with an untouched source row."""

    # Assumes the source table's id column is a non-negative integer.
    NEGATIVE_ID = "negative_id"
    # Integer ids used as stored, never negated: the source already keeps
    # negative ids and the base table's sequence hands out positive ones.
    NEGATIVE_SOURCE_POSITIVE_BASE_ID = "negative_source_positive_base_id"
    # Integer ids used as stored, never negated: the source keeps positive ids
    # and the base table's sequence counts down from -1.
    NEGATIVE_BASE_POSITIVE_SOURCE_ID = "negative_base_positive_source_id"
    UUID4 = "uuid4"
    UUID7 = "uuid7"
    UUID7_POLYFILL = "uuid7_polyfill"


PK_COMMENT = "Primary key generated by django-overlay; never collides with an id in the source table."


def _uuid_pk(default):
    return models.UUIDField(
        primary_key=True, default=default, editable=False, help_text=PK_COMMENT, db_comment=PK_COMMENT
    )


_FIELD_FACTORIES = {
    Strategy.UUID4: lambda: _uuid_pk(uuid.uuid4),
    Strategy.UUID7: lambda: _uuid_pk(uuid7),
    Strategy.UUID7_POLYFILL: lambda: _uuid_pk(uuid7),
}

# UUID7 needs Postgres 18+ for native uuidv7() — use UUID7_POLYFILL otherwise.
_PK_DEFAULT_TEMPLATES = {
    Strategy.UUID4: "pk_defaults/uuid4.sql.j2",
    Strategy.UUID7: "pk_defaults/uuid7.sql.j2",
    Strategy.UUID7_POLYFILL: "pk_defaults/uuid7_polyfill.sql.j2",
}


def default_id_field(strategy: Strategy) -> models.Field | None:
    factory = _FIELD_FACTORIES.get(strategy)
    return factory() if factory else None


def uses_uuid_ids(strategy: Strategy) -> bool:
    return strategy in _FIELD_FACTORIES


def default_pk_sql(strategy: Strategy) -> str | None:
    template_name = _PK_DEFAULT_TEMPLATES.get(strategy)
    return render(template_name) if template_name else None


def negates_source_ids(strategy: Strategy) -> bool:
    return strategy is Strategy.NEGATIVE_ID


def descending_base_ids(strategy: Strategy) -> bool:
    """Whether the base table's id sequence counts down rather than up."""
    return strategy is Strategy.NEGATIVE_BASE_POSITIVE_SOURCE_ID
